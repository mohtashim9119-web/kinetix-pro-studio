/// Embedded verbatim (WS1 Task 5 Slice D2's `fa-onnx-manifest.json`,
/// generated by `scripts/export-fa-onnx.py`) — same `include_str!`
/// convention `fa_onnx.rs::vocab_json_for` already uses for the per-language
/// vocab fixtures. The manifest's own `_provenance.note` says "Consumed by
/// Step T (deferred)" — Step T (the on-demand downloader) is still deferred;
/// this is a DIFFERENT consumer (a manual pre-use integrity check for a
/// model an operator placed by hand per the R-D manual-placement fallback),
/// not Step T itself.
const FA_ONNX_MANIFEST_JSON: &str = include_str!("../../scripts/fixtures/fa-onnx-manifest.json");

fn manifest_sha256_for(language: &str) -> Option<String> {
    let v: serde_json::Value = serde_json::from_str(FA_ONNX_MANIFEST_JSON).ok()?;
    v["models"][language]["sha256"].as_str().map(|s| s.to_string())
}

/// The manifest's own recorded `byteSize` for `language` — the input to the
/// WS1 Session G size precheck below. Already present in every entry of
/// `fa-onnx-manifest.json` (written by `scripts/export-fa-onnx.py` alongside
/// the sha256), so this costs nothing new to record and is an EXACT expected
/// value, not a heuristic bound.
fn manifest_byte_size_for(language: &str) -> Option<u64> {
    let v: serde_json::Value = serde_json::from_str(FA_ONNX_MANIFEST_JSON).ok()?;
    v["models"][language]["byteSize"].as_u64()
}

/// Identity of a file as cheaply as the filesystem can state it: path, byte
/// length, and mtime. The SAME technique `fa.rs::source_identity_key`
/// already uses for the durable-WAV cache (`name|size|mtime`) and that
/// `syncEngine.ts::getFileIdentity` uses on the TS side — reused rather than
/// invented, and carrying the same known limitation (a replacement that
/// preserves both size and mtime is not detected).
type ModelIdentity = (std::path::PathBuf, u64, Option<std::time::SystemTime>);

/// Memoized full-file digests, keyed on `ModelIdentity`.
///
/// IN-PROCESS ONLY, deliberately. It is never persisted, so every app start
/// re-hashes the model in full and no stale or poisoned entry can outlive a
/// restart. What it removes is the per-CALL tax: before this, every single
/// Apply Sync re-hashed ~1.26 GiB (measured ~5.25s release / ~77.43s debug,
/// WS1 Session F), model healthy or not.
///
/// It stores the COMPUTED DIGEST, not a boolean verdict — the equality
/// check against the manifest still runs on every call, so a cache hit can
/// never turn a mismatched model into an accepted one. It also memoizes a
/// BAD digest, which is what brings the repeat same-size-corruption case
/// under budget.
fn verified_digest_cache() -> &'static std::sync::Mutex<std::collections::HashMap<ModelIdentity, String>> {
    static CACHE: std::sync::OnceLock<
        std::sync::Mutex<std::collections::HashMap<ModelIdentity, String>>,
    > = std::sync::OnceLock::new();
    CACHE.get_or_init(|| std::sync::Mutex::new(std::collections::HashMap::new()))
}

/// Test-only: empties the memo so a test can measure a cold call.
#[cfg(test)]
pub(crate) fn reset_verified_digest_cache_for_tests() {
    if let Ok(mut m) = verified_digest_cache().lock() {
        m.clear();
    }
}

/// Hashes `path` and compares against the committed manifest's recorded
/// SHA-256 for `language`. Never panics — a missing manifest entry, an I/O
/// failure, and a genuine hash mismatch are all reported as a typed
/// `FaError` (`ModelHashMismatch`), not a crash. The mismatch case is the
/// real integrity check this function exists for: a `model.onnx` placed by
/// hand could be truncated, corrupted, or simply the wrong file.
///
/// WS1 SESSION G — FAIL-CLEAN BUDGET. Two cheap steps run BEFORE the full
/// ~1.26 GiB stream-hash, neither of which weakens the good case (a healthy
/// model is still hashed in full, and still compared in full):
///
///   1. SIZE PRECHECK against the manifest's own `byteSize`. A truncated,
///      empty, or simply wrong file is rejected from one `stat` — the
///      common real corruption (an interrupted download, the wrong file
///      placed by hand). Budget tier A: under 50 ms including the first
///      call. It does NOT accelerate a same-size byte flip, and is not
///      claimed to: that file still reaches the hash below.
///   2. DIGEST MEMO keyed on (path, size, mtime), in-process only. The
///      first call for a given file identity pays the full hash exactly
///      once; every later call in the same process is a map lookup. This
///      is what removes the per-Apply-Sync tax on the HEALTHY path (tier C)
///      and brings the repeat same-size-corruption case (tier B) under
///      budget. The comparison against the manifest still runs on every
///      call — the memo caches the digest, never the verdict.
fn verify_model_manifest(path: &Path, language: &str) -> Result<(), FaError> {
    let expected = manifest_sha256_for(language).ok_or_else(|| FaError {
        kind: FaErrorKind::ModelHashMismatch,
        message: format!("no manifest entry for language \"{language}\" in fa-onnx-manifest.json"),
    })?;

    // One `stat`, reused by both the size precheck and the memo key.
    let meta = std::fs::metadata(path).map_err(|e| FaError {
        kind: FaErrorKind::ModelHashMismatch,
        message: format!("failed to stat model at {}: {e}", path.display()),
    })?;
    let actual_size = meta.len();

    if let Some(expected_size) = manifest_byte_size_for(language) {
        if actual_size != expected_size {
            return Err(FaError {
                kind: FaErrorKind::ModelHashMismatch,
                message: format!(
                    "model at {} is {actual_size} bytes but the committed manifest for \
                     \"{language}\" records {expected_size} — wrong or truncated file. \
                     Re-download/re-export the model; do not trust a mismatched file.",
                    path.display()
                ),
            });
        }
    }

    let identity: ModelIdentity = (path.to_path_buf(), actual_size, meta.modified().ok());
    let cached = verified_digest_cache()
        .lock()
        .ok()
        .and_then(|m| m.get(&identity).cloned());

    let actual = match cached {
        Some(digest) => digest,
        None => {
            let digest = crate::sha256::hash_file(path).map_err(|e| FaError {
                kind: FaErrorKind::ModelHashMismatch,
                message: format!("failed to hash model at {}: {e}", path.display()),
            })?;
            if let Ok(mut m) = verified_digest_cache().lock() {
                m.insert(identity, digest.clone());
            }
            digest
        }
    };

    if actual != expected {
        return Err(FaError {
            kind: FaErrorKind::ModelHashMismatch,
            message: format!(
                "model at {} does not match the committed manifest for \"{language}\" — expected \
                 sha256 {expected}, got {actual}. Re-download/re-export the model; do not trust a \
                 mismatched file.",
                path.display()
            ),
        });
    }
    Ok(())
}

/// A reasonable temp filename extension from the caller-supplied hint.
/// `whisper.rs::transcode_to_wav` (ffmpeg) probes container format from the
/// file's actual content, not its extension, so an unrecognized hint still
/// works correctly — this only affects the temp filename's cosmetics.
fn extension_for(hint: &str) -> &'static str {
    match hint {
        "wav" | "audio/wav" | "audio/wave" | "audio/x-wav" => "wav",
        "mp3" | "audio/mpeg" | "audio/mp3" => "mp3",
        "ogg" | "audio/ogg" => "ogg",
        "flac" | "audio/flac" => "flac",
        "m4a" | "audio/mp4" | "audio/x-m4a" | "audio/aac" => "m4a",
        "aiff" | "audio/aiff" => "aiff",
        "webm" | "audio/webm" => "webm",
        _ => "bin",
    }
}

/// Raw-binary staging command for the `input_path` argument `fa_align_dev`
/// and `fa_align_production` now take.
///
/// Writes the invoke request's raw body bytes to a content-addressed
/// (SHA-256 of the bytes) path under `cache_dir_name` (a caller-owned
/// namespace, carried as the `cache-dir` request header, so a devtools call
/// and a real Apply-Sync call against the same audio content can never
/// collide on the same path — the two namespaces `fa_align_dev` and
/// `fa_align_production` each used to pass down to `resolve_wav_and_align`
/// before this command existed). `ext-hint` (optional; same values
/// `extension_for` below already accepts) picks the written file's
/// extension.
///
/// Content-addressing, not per-call/uuid'd, for the same reason
/// `resolve_wav_and_align`'s old inline version of this write was
/// content-addressed: `ensure_durable_wav`'s cache key is the SOURCE file's
/// own identity (name|size|mtime — `fa.rs::source_identity_key`), so a fresh
/// uuid'd temp file on every call would give every invocation of the SAME
/// clip a fresh mtime and defeat the durable cache before it ever got a
/// chance to hit.
///
/// Unlike the `audio_b64` shape this replaces, the payload is NOT
/// base64/JSON-encoded — the frontend passes a `Uint8Array` as the invoke
/// body (Tauri v2 raw request body). This removes the base64 encode (JS) +
/// inflated-string IPC transfer + base64 decode (Rust) that `ffmpeg.rs`'s
/// `ffmpeg_write_file_raw` doc comment already names as the cost this shape
/// avoids on the export path — applied here to a whole voiceover file
/// (potentially hundreds of MB uncompressed) instead of one export frame,
/// where the base64+JSON round trip's ~5-8x peak memory multiplication
/// across the JS heap and the WKWebView IPC bridge is far more likely to
/// matter.
#[tauri::command]
pub fn fa_stage_audio_raw(request: tauri::ipc::Request<'_>) -> Result<String, String> {
    let headers = request.headers();
    let cache_dir_name = headers
        .get("cache-dir")
        .and_then(|v| v.to_str().ok())
        .ok_or_else(|| "fa_stage_audio_raw: missing or invalid 'cache-dir' header".to_string())?;
    let ext_hint = headers
        .get("ext-hint")
        .and_then(|v| v.to_str().ok())
        .unwrap_or("");

    let bytes = match request.body() {
        tauri::ipc::InvokeBody::Raw(data) => data,
        tauri::ipc::InvokeBody::Json(_) => {
            return Err("fa_stage_audio_raw: expected a raw byte body, got JSON".to_string())
        }
    };

    let input_dir = std::env::temp_dir().join(cache_dir_name);
    fs::create_dir_all(&input_dir).map_err(|e| format!("create audio input cache dir: {e}"))?;
    let mut hasher = crate::sha256::Sha256::new();
    hasher.update(bytes);
    let content_key = crate::sha256::hex_digest(&hasher.finish());
    let input_path = input_dir.join(format!("{content_key}.{}", extension_for(ext_hint)));
    if !input_path.exists() {
        fs::write(&input_path, bytes).map_err(|e| format!("write audio: {e}"))?;
    }

    Ok(input_path.to_string_lossy().to_string())
}

/// Dev-only end-to-end FA entry point (WS1 Task 5 Slice D10): resolves +
/// manifest-verifies the model for `language`, then (WS1 Task 5 Slice D25
/// A1) obtains a 16kHz mono WAV via `fa::ensure_durable_wav` — the durable,
/// LRU-evicted cache under `app_local_data_dir()/fa-audio-cache/` (WS1 Task
/// 5 Slice D24 B1/B2) — rather than transcoding to a throwaway per-call WAV
/// as before, then delegates to the real `fa_align` unmodified.
///
/// `input_path` is a content-addressed file `fa_stage_audio_raw` (above)
/// already staged under `kinetix-fa-dev-inputs` — the frontend calls that
/// command first, with the raw audio bytes as the request body, and passes
/// the returned path here.
///
/// Neither the dev-input cache nor the durable WAV cache is cleaned up at
/// the end of this call (both are deliberately persistent, unlike the old
/// per-call temp directory) — that's the durable cache's whole point: a
/// second `fa_align_dev` call against the same clip should skip transcoding
/// entirely.
///
/// `chunks` (WS1 Task 5 Slice D11) replaces the pre-D11 `segments` param —
/// `src/services/faChunkPlan.ts` builds the ordered `{startSec, endSec,
/// text}` windows this now takes, one per `fa_align` forward pass, instead
/// of a single segment list implicitly aligned against the whole file.
/// Manifest verification above stays exactly once per `fa_align_dev` call
/// (unchanged) — the model-file SHA-256 is independent of, and unaffected
/// by, `fa_align`'s own internal per-chunk `Session` cache (`fa_onnx.rs`'s
/// `CachedSession`, keyed separately on file size+mtime for staleness).
#[tauri::command]
pub async fn fa_align_dev(
    app: tauri::AppHandle,
    state: tauri::State<'_, FaState>,
    model_cache: tauri::State<'_, FaModelCache>,
    input_path: String,
    chunks: Vec<FaChunkInput>,
    language: String,
    on_event: Channel<FaEvent>,
) -> Result<(), FaError> {
    resolve_wav_and_align(app, state, model_cache, input_path, chunks, language, on_event).await
}

/// Shared body behind both `fa_align_dev` (above) and the production,
/// capability-gated `fa_align_production` (`fa_production.rs`,
/// docs/work-in-progress.md §11 item 1): resolves + manifest-verifies the
/// model, obtains a durable 16kHz mono WAV via `fa::ensure_durable_wav` from
/// the already-staged `input_path` (see `fa_stage_audio_raw` above — the
/// caller runs that first and passes its result here), then delegates to
/// the real, unmodified `fa_align`. Extracted as its own function (rather
/// than duplicated) so the production command is provably running the exact
/// same resolve-then-delegate path this dev command has already been
/// live-verified against a real `AppHandle<Wry>` (D25 A1) — one
/// implementation, two thin command wrappers.
pub(crate) async fn resolve_wav_and_align(
    app: tauri::AppHandle,
    state: tauri::State<'_, FaState>,
    model_cache: tauri::State<'_, FaModelCache>,
    input_path: String,
    chunks: Vec<FaChunkInput>,
    language: String,
    on_event: Channel<FaEvent>,
) -> Result<(), FaError> {
    let model_path = fa_model_path(&app, &language)?;
    verify_model_manifest(&model_path, &language)?;

    let wav_path = crate::fa::ensure_durable_wav(&app, Path::new(&input_path)).await?;

    let audio_path = wav_path.to_string_lossy().to_string();
    fa_align(app, state, model_cache, audio_path, chunks, language, on_event).await
}

